#!/usr/bin/env bash
# 将 pnpm deploy 产物的 node_modules 从虚拟布局平铺为 npm 风格（v2 修复版）：
# - 删除所有顶层符号链接（bash rm 删链接无需 Windows 权限）
# - 把 .pnpm/<pkg>@<ver>/node_modules/ 下所有真实包复制到顶层（跟随链接，源必须完整）
# - 目标已存在则跳过（防止 cp 把源塞进已存在目录造成嵌套）
# - 复制后验证 package.json 存在，缺的计数报告
# - 最后删除 .pnpm 与 .modules.yaml
# 用法: bash scripts/flatten-node_modules.sh <api-runtime目录>
set -u
cd "$1" || exit 1
cd node_modules || exit 1

echo "== 删除顶层符号链接 =="
find . -maxdepth 1 -type l -delete
echo "剩余顶层条目：$(ls -a | grep -v '^\.$' | grep -v '^\.\.$' | grep -v '^\.pnpm$' | wc -l)"

echo "== 平铺 .pnpm 包 =="
declare -A seen
count=0
fail=0
for scope_or_pkg in .pnpm/*/node_modules/*/; do
  [ -e "$scope_or_pkg" ] || continue
  base=$(basename "$scope_or_pkg")
  if [[ "$base" == @* ]]; then
    for pkg in "$scope_or_pkg"*/; do
      [ -e "$pkg" ] || continue
      pkgname="$base/$(basename "$pkg")"
      [ -n "${seen[$pkgname]:-}" ] && continue
      seen[$pkgname]=1
      if [ -e "$pkgname" ]; then
        echo "跳过(已存在): $pkgname"
        continue
      fi
      mkdir -p "$(dirname "$pkgname")"
      cp -rL "$pkg" "$pkgname"
      if [ -f "$pkgname/package.json" ]; then
        count=$((count+1))
      else
        echo "缺package.json: $pkgname"
        fail=$((fail+1))
      fi
    done
  else
    [ -n "${seen[$base]:-}" ] && continue
    seen[$base]=1
    if [ -e "$base" ]; then
      echo "跳过(已存在): $base"
      continue
    fi
    cp -rL "$scope_or_pkg" "$base"
    if [ -f "$base/package.json" ]; then
      count=$((count+1))
    else
      echo "缺package.json: $base"
      fail=$((fail+1))
    fi
  fi
done

echo "== 清理 .pnpm 元数据 =="
rm -rf .pnpm .modules.yaml

echo "平铺完成：复制 $count 个包，缺 package.json $fail 个"
